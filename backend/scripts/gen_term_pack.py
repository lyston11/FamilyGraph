def main() -> None:
    existing = {code for code, _ in BUILTIN_ZH_CN_TERMS}
    additions = [(code, term, note) for code, term, note in PATTERNS if code not in existing]
    clashes = [code for code, _, _ in PATTERNS if code in existing]
    print(f"# 现有 {len(existing)} 条；新增候选 {len(additions)} 条；命中既有 {len(clashes)} 条")
    if clashes:
        print("# 命中既有（需人工核对是否覆盖）：" + ", ".join(clashes))
    print("BUILTIN_ZH_CN_ADDITIONS = [")
    for code, term, note in additions:
        suffix = f"  # {note}" if note else ""
        print(f'    ("{code}", "{term}"),{suffix}')
    print("]")
    print("BUILTIN_SYSTEM_ADDITIONS = [")
    for code, term, note in SYSTEM_ADDITIONS:
        suffix = f"  # {note}" if note else ""
        print(f'    ("{code}", "{term}"),{suffix}')
    print("]")


if __name__ == "__main__":
    main()
